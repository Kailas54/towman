// One-off asset pipeline: traces the brand PNGs into SVG paths and optimises imagery.
// Usage: node scripts/prepare-assets.mjs
import sharp from 'sharp';
import potrace from 'potrace';
import { mkdir, writeFile } from 'node:fs/promises';
import { promisify } from 'node:util';

const trace = promisify(potrace.trace);

const SRC = {
  logo: 'C:/Users/jerin.johnson/Downloads/Towman (2)/Towman Logo PNGs/Logo Color Variations-4.png',
  truck: 'C:/Users/jerin.johnson/Downloads/Towman/Towman New Mockups/Truck side design.jpg',
};

await mkdir('public/brand', { recursive: true });
await mkdir('public/img', { recursive: true });
await mkdir('src/brand', { recursive: true });

/** Returns a grayscale buffer where brand ink is black and the white background stays white. */
async function inkMask(input, width) {
  return sharp(input)
    .resize({ width })
    .flatten({ background: '#ffffff' })
    .greyscale()
    .threshold(200)
    .png()
    .toBuffer();
}

const mask = await sharp(await inkMask(SRC.logo, 4000)).trim({ threshold: 10 }).toBuffer({ resolveWithObject: true });
const { data: raw, info } = await sharp(mask.data).raw().toBuffer({ resolveWithObject: true });

// Find the first fully white column gap after the mark to split mark / wordmark.
const colHasInk = (x) => {
  for (let y = 0; y < info.height; y++) if (raw[(y * info.width + x) * info.channels] < 128) return true;
  return false;
};
let x = 0;
while (x < info.width && colHasInk(x)) x++;
const markEnd = x;
while (x < info.width && !colHasInk(x)) x++;
const wordStart = x;

async function traceRegion(left, width) {
  // sharp runs trim before extract inside one pipeline, so these must be separate passes.
  const cropped = await sharp(mask.data).extract({ left, top: 0, width, height: info.height }).png().toBuffer();
  const region = await sharp(cropped).trim({ threshold: 10 }).png().toBuffer({ resolveWithObject: true });
  const svg = await trace(region.data, { turdSize: 20, optTolerance: 0.3, threshold: 128, color: 'currentColor' });
  const d = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(' ');
  return { d, w: region.info.width, h: region.info.height };
}

const mark = await traceRegion(0, markEnd);
const word = await traceRegion(wordStart, info.width - wordStart);

const svgFile = (p, fill) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${p.w} ${p.h}"><path fill="${fill}" fill-rule="evenodd" d="${p.d}"/></svg>\n`;

await writeFile('public/brand/logomark.svg', svgFile(mark, '#FF6600'));
await writeFile('public/brand/wordmark.svg', svgFile(word, '#FFFFFF'));
await writeFile(
  'public/favicon.svg',
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${-mark.w * 0.2} ${-(mark.w * 1.4 - mark.h) / 2} ${mark.w * 1.4} ${mark.w * 1.4}"><rect x="${-mark.w * 0.2}" y="${-(mark.w * 1.4 - mark.h) / 2}" width="${mark.w * 1.4}" height="${mark.w * 1.4}" rx="${mark.w * 0.3}" fill="#00159B"/><path fill="#FF6600" fill-rule="evenodd" d="${mark.d}"/></svg>\n`,
);

await writeFile(
  'src/brand/paths.ts',
  `// Generated by scripts/prepare-assets.mjs — do not edit by hand.
export const LOGOMARK = { d: ${JSON.stringify(mark.d)}, w: ${mark.w}, h: ${mark.h} } as const;
export const WORDMARK = { d: ${JSON.stringify(word.d)}, w: ${word.w}, h: ${word.h} } as const;
export const LOGO_GAP = ${(wordStart - markEnd) / info.height};
`,
);

await sharp(SRC.truck).resize({ width: 1600 }).webp({ quality: 82 }).toFile('public/img/towman-truck.webp');
await sharp(SRC.truck).resize({ width: 1200 }).jpeg({ quality: 80, mozjpeg: true }).toFile('public/img/og-image.jpg');

